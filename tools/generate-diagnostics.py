#!/usr/bin/env python3
"""Generate diagnostic references from the language's diagnostic declarations."""

import argparse
import json
from pathlib import Path
import re
import sys


ROOT = Path(__file__).resolve().parents[1] / "languages" / "kira"
MARKER = "<!-- hand-written: diagnostic standards -->"


def outputs():
    registry = ROOT / "definitions/diagnostic-registry.json"
    if registry.exists():
        table = json.loads(registry.read_text())
        lines = ["// Generated by tools/generate-diagnostics.py.", "", "enum Diagnostic {"]
        lines.extend("    " + row["name"] for row in table)
        lines.extend(["", "    function code(borrow self) -> Int {", "        return diagnosticCode(self)", "    }", "}"])
        yield ROOT / "definitions/diagnostics.klfd", "\n".join(lines) + "\n"
        code = ["// Generated by tools/generate-diagnostics.py.", "", "function diagnosticCode(diagnostic: Diagnostic) -> Int {", "    match diagnostic {"]
        code.extend(f'        {row["name"]} -> return {row["code"]}' for row in table)
        code.extend(["    }", "}"])
        yield ROOT / "definitions/diagnostic-codes.klfd", "\n".join(code) + "\n"
    language = (ROOT / "definitions/language.klfd").read_text()
    specifications = re.findall(
        r'DiagnosticSpec\s*\{\s*code\s*=\s*(\d+),\s*severity\s*=\s*\.(\w+),'
        r'\s*title\s*=\s*"((?:\\.|[^"\\])*)",'
        r'\s*explanation\s*=\s*"((?:\\.|[^"\\])*)"(?:\s*,\s*help\s*=\s*"(?:\\.|[^"\\])*")?\s*\}',
        language,
    )
    if not specifications:
        raise ValueError("no diagnostic specifications found")
    codes = [int(row[0]) for row in specifications]
    if len(codes) != len(set(codes)):
        raise ValueError("duplicate diagnostic numbers")
    declarations = (ROOT / "definitions/diagnostics.klfd").read_text()
    mapped = re.findall(r'\b(\w+)\s*->\s*return\s+(\d+)', declarations)
    if registry.exists():
        mapped = [(row["name"], str(row["code"])) for row in table]
    missing = {int(code) for _, code in mapped} - set(codes)
    if missing:
        raise ValueError(f"diagnostic specifications missing: {sorted(missing)}")
    rows = [
        "# Diagnostic codes",
        "",
        "Generated from `definitions/language.klfd` by `tools/generate-diagnostics.py`.",
        "Do not edit this table by hand.",
        "",
        "The compiler reports a numeric code and a source range. The thousands",
        "band identifies the phase: 1xxx lexer, 2xxx parser, 3xxx semantics,",
        "4xxx packages, and 5xxx macros. Warnings do not fail a compilation.",
        "",
        "| Code | Severity | Message | Explanation |",
        "| --- | --- | --- | --- |",
    ]
    for code, severity, title, explanation in sorted(specifications, key=lambda row: int(row[0])):
        cells = [code, severity.lower(), title, explanation]
        cells = [cell.replace('\\"', '"').replace("|", "\\|").replace("\n", " ") for cell in cells]
        rows.append("| " + " | ".join(cells) + " |")
    # The standards after the marker are written by hand and kept as they are.
    docs_path = ROOT / "docs/diagnostics.md"
    kept = ""
    if docs_path.exists():
        existing = docs_path.read_text()
        if MARKER in existing:
            kept = "\n" + existing[existing.index(MARKER):]
    yield docs_path, "\n".join(rows) + "\n" + kept

    vocabulary = (ROOT / "std/Foundation/app/diagnostics/Diagnostics.kira").read_text()
    cases = re.findall(r'^\s+(K[A-Z]+\d+)\s*$', vocabulary, re.MULTILINE)
    if not cases or len(cases) != len(set(cases)):
        raise ValueError("invalid Foundation diagnostic vocabulary")
    body = [
        "// Generated from Diagnostics.kira by tools/generate-diagnostics.py.",
        "",
        "function kiraErrorFromCode(text: borrow String) -> KiraError {",
        "    return match text {",
    ]
    body.extend(f'        "{case}" -> .{case}' for case in cases)
    body.extend(["        else -> .Unrecognized", "    }", "}"])
    yield ROOT / "std/Foundation/app/diagnostics/DiagnosticCodes.kira", "\n".join(body) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    arguments = parser.parse_args()
    stale = []
    for path, text in outputs():
        if arguments.check:
            if not path.exists() or path.read_text() != text:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.write_text(text)
    if stale:
        print("stale generated diagnostics: " + ", ".join(stale), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
